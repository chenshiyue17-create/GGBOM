#!/bin/bash
# =============================================================================
# view_latest_logs.sh
# 实时跟踪最新的 UE 构建与运行时日志
# =============================================================================

LOG_DIR="/Users/cc/Desktop/GGBOM/xxxx/Saved/Logs"

echo "================================================================"
echo "📄 当前最新可用日志文件列表:"
echo "================================================================"
ls -lt "${LOG_DIR}" 2>/dev/null | head -n 10 || echo "暂无日志文件"

echo ""
echo "================================================================"
echo "🔍 正在跟踪最新运行日志 (按 Ctrl+C 退出)..."
echo "================================================================"
LATEST_LOG=$(ls -t "${LOG_DIR}"/*.log 2>/dev/null | head -n 1 || true)

if [ -n "${LATEST_LOG}" ]; then
    echo "打开日志: ${LATEST_LOG}"
    tail -f "${LATEST_LOG}"
else
    echo "未找到 .log 文件"
fi
